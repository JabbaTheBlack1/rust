package com.rustbuild.build;

/** Точка стыковки элемента (локальные координаты). dir - направление наружу в градусах (см. Geo). */
public record Socket(Kind kind, double x, double y, double z, double dir) {
    public enum Kind {
        /** Верхний край плиты (фундамент/пол): к нему крепятся соседние плиты, стены, ступени. */
        EDGE_TOP,
        /** Нижний край плиты/крыши: садится на верх стены. */
        EDGE_BOTTOM,
        /** Верх стены: на него садятся полы и крыши. */
        WALL_TOP,
        /** Центр верха квадратной плиты: сюда ставятся лестницы. */
        CELL,
        /** Точка, которой стена/лестница/ступени встают на плиту. */
        BASE_PLUG
    }
}
